export type MessageKey = keyof typeof messages['zh-TW']

function detectLocale(): Locale {
  const stored = globalThis.localStorage?.getItem(STORAGE_KEY)
  if (stored === 'zh-TW' || stored === 'en') return stored

  const browserLanguage = globalThis.navigator?.language?.toLowerCase() || ''
  if (browserLanguage.startsWith('en')) return 'en'
  return 'zh-TW'
}

const currentLocale = ref<Locale>(detectLocale())

watchEffect(() => {
  globalThis.localStorage?.setItem(STORAGE_KEY, currentLocale.value)
  if (globalThis.document) {
    document.documentElement.lang = currentLocale.value
  }
})

function translate(key: MessageKey, params?: Record<string, string | number>) {
  let message: string = messages[currentLocale.value][key] || messages['zh-TW'][key] || key
  if (!params) return message

  for (const [name, value] of Object.entries(params)) {
    message = message.replaceAll(`{${name}}`, String(value))
  }
  return message
}

export function useI18n() {
  const localeLabel = computed(() => currentLocale.value === 'en' ? 'English' : '中文')

  function setLocale(locale: Locale) {
    currentLocale.value = locale
  }

  function toggleLocale() {
    currentLocale.value = currentLocale.value === 'en' ? 'zh-TW' : 'en'
  }

  return {
    locale: currentLocale,
    localeLabel,
    setLocale,
    t: translate,
    toggleLocale,
  }
}

export function getMessage(key: MessageKey, params?: Record<string, string | number>) {
  return translate(key, params)
}
